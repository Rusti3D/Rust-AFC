    /// _calc_length: 'reset', +/-delta or an absolute length
    pub fn calc_length(&self, config_length: f64, current_length: f64, new_length: &str) -> KResult<f64> {
        if new_length.to_lowercase() == "reset" {
            return Ok(config_length);
        }
        if new_length.starts_with(['+', '-']) {
            return Ok(match kaliru::pyfmt::py_float(new_length) {
                Some(v) => current_length + v,
                None => {
                    self.logger().error(&AFC_FUNCTIONS_AFCFUNCTION__CALC_LENGTH, &format!("Invalid length: {}", new_length));
                    current_length
                }
            });
        }
        super::utils::py_float_of(&PyVal::Str(new_length.to_string()))
    }

