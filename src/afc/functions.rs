    /// Back to absolute coordinates and extrusion if relative
    pub fn check_absolute_mode(&self, func_name: &str) -> KResult<()> {
        let afc = self.afc();
        let c = &AFC_FUNCTIONS_AFCFUNCTION_CHECK_ABSOLUTE_MODE;
        self.log_toolhead_pos(&format!("{}: check absolute mode, POS:", func_name))?;
        let gm = afc.gcode_move()?;
        if !gm.absolute_coord.get() {
            self.logger().debug(c, "Printer coords not in absolute mode, setting to absolute mode");
            gm.absolute_coord.set(true);
        }
        if !gm.absolute_extrude.get() {
            self.logger().debug(c, "Printer extruder not in absolute mode, setting to absolute mode");
            gm.absolute_extrude.set(true);
        }
        Ok(())
    }

    /// The extruder's past position, when greater than the previous one
    pub fn get_extruder_pos(&self, eventtime: Option<f64>, past_extruder_position: Option<f64>, extruder: Option<Rc<dyn kaliru::toolhead::ExtraAxis>>) -> KResult<f64> {
        let afc = self.afc();
        let eventtime = eventtime.unwrap_or_else(|| afc.reactor.monotonic());
        let mcu = self.mcu.borrow().clone().ok_or_else(|| no_attr("NoneType", "estimated_print_time"))?;
        let print_time = mcu.estimated_print_time(eventtime);
        let extruder = match extruder {
            Some(e) => e,
            None => afc.toolhead()?.get_extruder(),
        };
        let last_extruder_position = extruder.find_past_position(print_time);
        Ok(match past_extruder_position {
            Some(p) if last_extruder_position <= p => p,
            _ => last_extruder_position,
        })
    }

    pub fn sync_print_time(&self) -> KResult<()> {
        let toolhead = self.printer.lookup::<kaliru::toolhead::ToolHead>("toolhead")?;
        let print_time = toolhead.get_last_move_time()?;
        if self.next_cmd_time.get() > print_time {
            toolhead.dwell(self.next_cmd_time.get() - print_time)?;
        } else {
            self.next_cmd_time.set(print_time);
        }
        Ok(())
    }

    pub fn do_enable(&self, enable: bool, stepper_name: &str) -> KResult<()> {
        self.sync_print_time()?;
        let stepper_enable = self.printer.lookup::<kaliru::extras::stepper_enable::PrinterStepperEnable>("stepper_enable")?;
        let se = stepper_enable.lookup_enable(stepper_name)?;
        if enable {
            se.motor_enable(self.next_cmd_time.get())?;
        } else {
            se.motor_disable(self.next_cmd_time.get())?;
        }
        self.sync_print_time()
    }

    /// (error, message) of the TD-1 devices (or one serial)
    pub fn check_for_td1_error(&self, serial_number: Option<&str>, print_error: bool) -> KResult<(bool, String)> {
        let moonraker = self.afc().moonraker.borrow().clone().ok_or_else(|| no_attr("NoneType", "get_td1_data"))?;
        let td1_data = moonraker.get_td1_data();
        Ok(self.check_td1_error_in_data(td1_data.as_ref(), serial_number, print_error))
    }

    fn check_td1_error_in_data(&self, td1_data: Option<&PyVal>, serial_number: Option<&str>, print_error: bool) -> (bool, String) {
        let mut error_occurred = false;
        let mut error_message = String::new();
        if let Some(PyVal::Dict(d)) = td1_data.map(|v| v.get()) {
            for (serial, data) in d {
                let err = match data.get() {
                    PyVal::Dict(dd) => dd.get("error").cloned().filter(|e| !matches!(e, PyVal::None)),
                    _ => None,
                };
                if let Some(err) = err {
                    if serial_number.is_none_or(|s| s == serial.as_ref()) {
                        error_message = format!("Error with TD-1 Serial: {}, please fix error with TD-1 and run 'AFC_RESET_TD1 SERIAL={}' macro.\n", serial, serial);
                        error_message += "Some errors can occur when first booting machine and filament is in TD-1 device\n";
                        error_message += &format!("Reported Error: {}", err.str());
                        error_occurred = true;
                        if print_error {
                            self.logger().error(&AFC_FUNCTIONS_AFCFUNCTION__CHECK_TD1_ERROR_IN_DATA, &error_message);
                        }
                    }
                }
            }
        }
        (error_occurred, error_message)
    }

    pub fn check_for_td1_id(&self, serial_number: Option<&str>) -> KResult<(bool, String)> {
        let moonraker = self.afc().moonraker.borrow().clone().ok_or_else(|| no_attr("NoneType", "get_td1_data"))?;
        Ok(self.check_td1_id_in_data(moonraker.get_td1_data().as_ref(), serial_number))
    }

    pub fn check_td1_id_in_data(&self, td1_data: Option<&PyVal>, serial_number: Option<&str>) -> (bool, String) {
        let found = match (td1_data.map(|v| v.get()), serial_number) {
            (Some(PyVal::Dict(d)), Some(s)) => d.contains_key(s),
            _ => false,
        };
        if !found {
            return (false, format!("TD-1 Device ID ({}) supplied but ID not found.", py_opt_str(serial_number)));
        }
        let (no_error, error_message) = self.check_td1_error_in_data(td1_data, serial_number, false);
        (!no_error, error_message)
    }

    /// The parameter (default: the current value); a new value is written
    /// to the config
    #[allow(clippy::too_many_arguments)] // (python's signature)
    pub fn gcode_get_value(&self, gcmd: &GCodeCommand, kind: &str, variable: &PyVal, variable_name: &str, section_name: &str, key_name: Option<&str>, cast_to_bool: bool) -> KResult<PyVal> {
        let old_value = variable.clone();
        let mut new_value = match kind {
            "get_float" => PyVal::Float(gcmd.get_float(variable_name, Some(super::utils::py_float_of(variable)?), Lim::new())?),
            "get_int" => PyVal::Int(gcmd.get_int(variable_name, Some(super::utils::py_int_of(variable)?), Lim::new())?),
            _ => PyVal::Str(gcmd.get_or(variable_name, &variable.str())),
        };
        let key_name = key_name.map(|k| k.to_string()).unwrap_or_else(|| variable_name.to_lowercase());
        if cast_to_bool {
            new_value = PyVal::Bool(new_value.truthy());
        }
        if !old_value.py_eq(&new_value) {
            self.logger().info(&AFC_FUNCTIONS_AFCFUNCTION_GCODE_GET_VALUE, &format!("Updating {}, New: {} Old: {}", key_name, new_value.str(), old_value.str()));
            self.config_rewrite(section_name, &key_name, &new_value, "")?;
        }
        Ok(new_value)
    }

    /// "1,0,0,0" -> "#ff0000"
    pub fn hex_convert(&self, tmp: &str) -> KResult<String> {
        let led: Vec<&str> = tmp.split(',').collect();
        let chan = |i: usize| -> KResult<i64> {
            let s = led.get(i).ok_or_else(|| KError::Py("IndexError".into(), "list index out of range".into()))?;
            let f = super::utils::py_float_of(&PyVal::Str(s.to_string()))?;
            Ok(if f > 0.0 { (255.0 * f).trunc() as i64 } else { 0 })
        };
        Ok(format!("#{:02x}{:02x}{:02x}", chan(0)?, chan(1)?, chan(2)?))
    }

    /// "FF0000" -> [1.0, 0.0, 0.0, 0.0]
    pub fn hex_to_led_string(&self, led_value: &str) -> KResult<Vec<f64>> {
        let mut new_value = vec![];
        let chars: Vec<char> = led_value.chars().collect();
        for chunk in chars.chunks(2) {
            let s: String = chunk.iter().collect();
            let v = i64::from_str_radix(&s, 16).map_err(|_| KError::Py("ValueError".into(), format!("invalid literal for int() with base 16: {}", super::py_repr(&s))))?;
            new_value.push(v as f64 / 255.0);
        }
        new_value.push(if led_value == "FFFFFF" { 1.0 } else { 0.0 });
        Ok(new_value)
    }

    fn create_options(macro_name: &str, options: &[MacroOption]) -> String {
        let mut option_str = String::new();
        for (key, kind, default) in options {
            option_str += &format!("{{%set dummy=params.{}|default('{}')|{}%}}\n", key, default, kind);
        }
        option_str += &format!("_{} {{rawparams}}", macro_name);
        option_str
    }

    /// gcode.register_mux_command (as _NAME when the macro shows in the web
    /// interfaces) and the web interfaces' macro
    #[allow(clippy::too_many_arguments)] // (python's signature)
    pub fn register_mux_command(&self, show_macros: bool, macro_name: &str, key: &str, value: &str, command: Handler, description: &str, options: Option<&[MacroOption]>) -> KResult<()> {
        let gcode = self.printer.lookup::<GCodeDispatch>("gcode")?;
        let name = if show_macros { format!("_{}", macro_name) } else { macro_name.to_string() };
        gcode.register_mux_command(&name, key, Some(value), command, Some(description))?;
        self.register_klipper(show_macros, macro_name, description, options)
    }

    pub fn register_commands(&self, show_macros: bool, macro_name: &str, command: Handler, description: &str, options: Option<&[MacroOption]>) -> KResult<()> {
        let gcode = self.printer.lookup::<GCodeDispatch>("gcode")?;
        let name = if show_macros { format!("_{}", macro_name) } else { macro_name.to_string() };
        gcode.register_command(&name, Some(command), false, Some(description))?;
        self.register_klipper(show_macros, macro_name, description, options)
    }

    /// The [gcode_macro NAME] section injected so the command shows up as a
    /// macro in the web interfaces
    fn register_klipper(&self, show_macros: bool, macro_name: &str, description: &str, options: Option<&[MacroOption]>) -> KResult<()> {
        if !show_macros {
            return Ok(());
        }
        let name = format!("gcode_macro {}", macro_name);
        {
            let mut fc = self.config.fileconfig.borrow_mut();
            if !fc.has_section(&name) {
                fc.add_section(&name)?;
                fc.set(&name, "description", description)?;
                let gcode = match options {
                    Some(o) => Self::create_options(macro_name, o),
                    None => format!("_{}", macro_name),
                };
                fc.set(&name, "gcode", &gcode)?;
                let opts = fc.options(&name)?;
                let mut at = self.config.access_tracking.borrow_mut();
                for option in opts {
                    at.insert((name.to_lowercase(), option.to_lowercase()), PyVal::Int(1));
                }
            }
        }
        self.printer.load_object(&self.config, &name, true)?;
        Ok(())
    }

