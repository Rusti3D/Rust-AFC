    fn cmd_afc_lane_reset(self: &Rc<Self>, gcmd: &GCodeCommand) -> KResult<()> {
        let afc = self.afc();
        let logger = self.logger();
        let c = &AFC_FUNCTIONS_AFCFUNCTION_CMD_AFC_LANE_RESET;
        let prompt = AfcPrompt::new(&logger);
        let lane = gcmd.get_opt("LANE");
        let long_dis = gcmd.get_or("DISTANCE", "50");
        let Some(lane) = lane.filter(|l| !l.is_empty()) else {
            prompt.p_end();
            afc.error.afc_error(c, "No lane selected to reset, please provide a lane to reset.", false, None)?;
            return Ok(());
        };
        let Some(cur_lane) = afc.lane(&lane) else {
            prompt.p_end();
            afc.error.afc_error(c, &format!("'{}' is not a valid lane", lane), false, None)?;
            return Ok(());
        };
        let long_dis = match kaliru::pyfmt::py_float(&long_dis) {
            Some(v) if v > 0.0 => v,
            _ => {
                prompt.p_end();
                afc.error.afc_error(c, "DISTANCE must be a valid number.", false, None)?;
                return Ok(());
            }
        };
        let cur_hub = cur_lane.hub_obj()?;
        let short_move = cur_lane.short_move_dis() * 2.0;
        if !cur_hub.state() {
            prompt.p_end();
            afc.error.afc_error(c, &format!("Hub is already clear while trying to reset '{}'", lane), false, None)?;
            return Ok(());
        }
        if let Some(tool_load) = self.get_current_lane_obj() {
            prompt.p_end();
            afc.error.afc_error(c, &format!("Toolhead is loaded with '{}', unload or check sensor before resetting lane", tool_load.name), false, None)?;
            return Ok(());
        }
        prompt.p_end();
        // Stepperless units retract through their own reset command
        if let Some(reset_cmd) = cur_lane.unit_obj()?.lane_reset_command(&cur_lane) {
            afc.gcode.run_script_from_command(&reset_cmd)?;
            return Ok(());
        }
        afc.gcode.respond_info(&format!("Resetting {} to hub", lane), true);
        let mut pos = 0.0;
        cur_lane.unit_obj()?.move_to_hub(&cur_lane, long_dis, MoveDirection::Neg, afc.homing_enabled, SpeedMode::from_assist(AssistActive::Yes))?;
        while cur_hub.state() {
            cur_lane.move_lane(-short_move, cur_lane.short_moves_speed(), cur_lane.short_moves_accel(), true)?;
            pos -= short_move;
            if !cur_lane.raw_load_state() {
                afc.error.afc_error(c, &format!("'{}' failed to reset to hub, load switch became false during reset", cur_lane.name), false, None)?;
                return Ok(());
            }
            if !cur_lane.prep_state.get() {
                afc.error.afc_error(c, &format!("'{}' failed to reset to hub, prep switch became false during reset", cur_lane.name), false, None)?;
                return Ok(());
            }
            if f64::abs(pos) >= cur_hub.afc_bowden_length.get() {
                afc.error.afc_error(c, &format!("'{}' failed to reset to hub", cur_lane.name), false, None)?;
                return Ok(());
            }
        }
        cur_lane.move_lane(-cur_hub.hub_clear_move_dis(), cur_lane.short_moves_speed(), cur_lane.short_moves_accel(), true)?;
        cur_lane.loaded_to_hub.set(true);
        cur_lane.do_enable(false)?;
        afc.gcode.respond_info(&format!("{} reset to hub, take necessary action", lane), true);
        Ok(())
    }

