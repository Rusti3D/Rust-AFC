/// re.compile("^\\[\\s*{section}\\s*\\]") (the section is a literal here:
/// AFC section names have no regex characters)
fn regex_lite_section(section: &str) -> impl Fn(&str) -> bool + '_ {
    move |line: &str| {
        let Some(rest) = line.strip_prefix('[') else { return false };
        let rest = rest.trim_start_matches(char::is_whitespace);
        let Some(rest) = rest.strip_prefix(section) else { return false };
        rest.trim_start_matches(char::is_whitespace).starts_with(']')
    }
}

/// afcDeltaTime: wall clock deltas of a load / unload / toolchange
pub struct DeltaTime {
    logger: Rc<AfcLogger>,
    start_time: Cell<Option<f64>>,
    last_time: Cell<Option<f64>>,
    major_delta_time: Cell<Option<f64>>,
    delta_time: Cell<f64>,
}

fn now() -> f64 {
    std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| d.as_secs_f64()).unwrap_or(0.0)
}

impl DeltaTime {
    pub fn new(logger: Rc<AfcLogger>) -> DeltaTime {
        DeltaTime { logger, start_time: Cell::new(None), last_time: Cell::new(None), major_delta_time: Cell::new(None), delta_time: Cell::new(0.0) }
    }

    pub fn set_start_time(&self) {
        // (datetime.now(): microsecond resolution)
        let t = (now() * 1e6).trunc() / 1e6;
        self.major_delta_time.set(Some(t));
        self.last_time.set(Some(t));
        self.start_time.set(Some(t));
    }

    /// (caller is the function python's afcDeltaTime logs from)
    pub fn log_with_time(&self, _caller: &Code, msg: &str, debug: bool) {
        let c = &AFC_FUNCTIONS_AFCDELTATIME_LOG_WITH_TIME;
        match (self.last_time.get(), self.start_time.get()) {
            (Some(last), Some(start)) => {
                let curr_time = (now() * 1e6).trunc() / 1e6;
                self.delta_time.set(curr_time - last);
                let total_time = curr_time - start;
                let msg = format!("{} (\u{394}t:{:.3}s, t:{:.3})", msg, self.delta_time.get(), total_time);
                if debug {
                    self.logger.debug(c, &msg);
                } else {
                    self.logger.info(c, &msg);
                }
                self.last_time.set(Some(curr_time));
            }
            _ => self.logger.debug(c, "Error in log_with_time function unsupported operand type(s) for -: 'datetime.datetime' and 'NoneType'"),
        }
    }

    pub fn log_major_delta(&self, _caller: &Code, msg: &str, _debug: bool) -> f64 {
        let c = &AFC_FUNCTIONS_AFCDELTATIME_LOG_MAJOR_DELTA;
        self.delta_time.set(0.0);
        match self.major_delta_time.get() {
            Some(major) => {
                let curr_time = (now() * 1e6).trunc() / 1e6;
                self.delta_time.set(curr_time - major);
                self.logger.info(c, &format!("{} t:{:.3}", msg, self.delta_time.get()));
                self.major_delta_time.set(Some(curr_time));
            }
            None => self.logger.debug(c, "Error in log_major_delta function 'afcDeltaTime' object has no attribute 'major_delta_time'"),
        }
        self.delta_time.get()
    }

    pub fn log_total_time(&self, _caller: &Code, msg: &str) -> f64 {
        let c = &AFC_FUNCTIONS_AFCDELTATIME_LOG_TOTAL_TIME;
        match self.start_time.get() {
            Some(start) => {
                let total_time = (now() * 1e6).trunc() / 1e6 - start;
                self.logger.info(c, &format!("{} t:{:.3}", msg, total_time));
                total_time
            }
            None => {
                self.logger.debug(c, "Error in log_total_time function unsupported operand type(s) for -: 'datetime.datetime' and 'NoneType'");
                0.0
            }
        }
    }
}

