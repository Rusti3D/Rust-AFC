    fn cmd_test_lane(self: &Rc<Self>, gcmd: &GCodeCommand) -> KResult<()> {
        let afc = self.afc();
        let logger = self.logger();
        let c = &AFC_FUNCTIONS_AFCFUNCTION_CMD_TEST_LANE;
        let iterations = gcmd.get_int("ITERATION", Some(1), Lim::new())?;
        let lane = gcmd.get_opt("LANE");
        let prompt = AfcPrompt::new(&logger);
        prompt.p_end();
        if let Some(lane) = lane {
            if afc.park.get() {
                if let Some(p) = &afc.park_cmd {
                    afc.gcode.run_script_from_command(p)?;
                }
            }
            logger.info(c, &format!("Starting test for lane(s): {}", lane));
            let lane_obj = afc.lane(&lane);
            if lane != "all" {
                logger.info(c, &format!("Running {} iterations for lane: {}", iterations, lane));
                let lane_obj = lane_obj.ok_or_else(|| no_attr("NoneType", "name"))?;
                for i in 0..iterations {
                    afc.save_pos()?;
                    logger.info(c, &format!("Loading lane: {}", lane));
                    afc.change_tool(&lane_obj, None, true, None)?;
                    if !afc.error_state.get() {
                        logger.info(c, &format!("Lane {} loaded successfully (Iteration {})", lane, i + 1));
                    } else {
                        logger.error(c, &format!("Failed to load lane {} on iteration {}", lane, i + 1));
                        afc.error.reset_failure()?;
                        break;
                    }
                    self.safe_extrude(&afc.test_extrude_amt, 100)?;
                    logger.info(c, &format!("Unloading lane {}", lane));
                    if !afc.tool_unload(&lane_obj, true, false)? {
                        afc.afc_stats()?.increase_unload_error_count(&afc)?;
                    }
                    if !afc.error_state.get() {
                        logger.info(c, &format!("Lane {} unloaded successfully for iteration {}/{}", lane, i + 1, iterations));
                        afc.restore_pos(true)?;
                    } else {
                        logger.error(c, &format!("Failed to unload lane {} at iteration {}", lane, i + 1));
                        afc.error.reset_failure()?;
                        return Ok(());
                    }
                }
            } else {
                let mut loaded_lanes: Vec<Rc<AfcLane>> = afc.lanes.borrow().values().filter(|l| l.load_state() && l.prep_state.get()).cloned().collect();
                logger.info(c, &format!("Running {} iterations for all loaded lanes", iterations));
                let mut last: Option<Rc<AfcLane>> = None;
                for i in 0..iterations {
                    super::utils::shuffle(&mut loaded_lanes);
                    for lane_obj in &loaded_lanes {
                        logger.info(c, &format!("Loading lane: {}", lane_obj.name));
                        afc.change_tool(lane_obj, None, true, None)?;
                        if !afc.error_state.get() {
                            logger.info(c, &format!("Lane {} loaded successfully", lane_obj.name));
                        } else {
                            logger.error(c, &format!("Failed to load lane {}", lane_obj.name));
                            afc.error.reset_failure()?;
                            return Ok(());
                        }
                        self.safe_extrude(&afc.test_extrude_amt, 100)?;
                        logger.info(c, &format!("Unloading lane {}", lane_obj.name));
                        last = Some(lane_obj.clone());
                    }
                    if i == iterations - 1 {
                        logger.info(c, &format!("Finished testing with {} iterations for all loaded lanes", iterations));
                        let lane_obj = last.clone().ok_or_else(|| {
                            KError::Py("NameError".into(), "cannot access free variable 'lane_obj' where it is not associated with a value in enclosing scope".into())
                        })?;
                        if !afc.tool_unload(&lane_obj, true, false)? {
                            afc.afc_stats()?.increase_unload_error_count(&afc)?;
                        }
                    }
                }
            }
        }
        prompt.p_end();
        Ok(())
    }

