    /// (checked, calibrated lanes, messages); canvas units cannot calibrate
    fn lane_calibration(&self, lanes: &str, unit: Option<&str>, tol: f64, dis: f64) -> KResult<(bool, Vec<String>, Vec<String>)> {
        let afc = self.afc();
        let c = &AFC_FUNCTIONS_AFCFUNCTION__LANE_CALIBRATION;
        let mut calibrated = vec![];
        let mut additional_msg = vec![];
        let mut calibrate_lanes: Vec<Rc<AfcLane>> = vec![];
        let mut checked = false;
        self.logger().info(c, "Starting AFC distance Calibrations");
        if lanes != "all" {
            if let Some(l) = afc.lane(lanes) {
                calibrate_lanes.push(l);
            }
        } else if unit.is_none() {
            calibrate_lanes.extend(afc.lanes.borrow().values().cloned());
        } else if let Some(u) = unit.and_then(|u| afc.units.borrow().get(u).cloned()) {
            calibrate_lanes.extend(u.lanes.borrow().values().cloned());
        }
        let mut calibration_info: kaliru::IndexMap<String, (Vec<String>, String)> = kaliru::IndexMap::default();
        for lane in calibrate_lanes {
            if lane.extruder_obj()?.is_standalone() {
                self.logger().info(c, &format!("{} is a standalone lane, skipping calibration", lane.name));
                continue;
            }
            if !lane.load_state() || !lane.prep_state.get() {
                self.logger().info(c, &format!("{} not loaded skipping to next loaded lane", lane.name));
                continue;
            }
            let (ok, msg, pos) = if lane.is_direct_hub() { lane.unit_obj()?.calibrate_bowden(&lane, dis, tol)? } else { lane.unit_obj()?.calibrate_lane(&lane, tol)? };
            checked = ok;
            if !checked {
                afc.error.afc_error(c, &msg, false, None)?;
                let reset_lane = lane.hub_obj_opt().map(|h| h.state()).unwrap_or(false);
                self.afc_cali_fail(&lane.name, Some(PyVal::Float(pos.abs())), pos != 0.0 && reset_lane, "AFC Calibration Failed", &msg)?;
                return Ok((checked, vec![], vec![]));
            }
            if msg == "calibration_lane" {
                let unit = lane.unit_obj()?;
                let entry = calibration_info.entry(unit.name.clone()).or_insert_with(|| (vec![], unit.calibration_lane_message()));
                entry.0.push(lane.name.clone());
            } else {
                calibrated.push(lane.name.clone());
            }
        }
        for (lanes, msg) in calibration_info.values() {
            additional_msg.push(msg.replace("{lanes}", &lanes.join(", ")));
        }
        self.logger().info(c, "Lane calibration Done!");
        Ok((checked, calibrated, additional_msg))
    }

